// The UI icons: drawn by hand in visual-atelier (schemes/pomelo/marks/icons.mjs → src/vendor/pomelo/marks/icons/, Dawn Plan ·
// Phase 7), one stroke on a 24 grid, following the text colour. They keep the names the code has always called them by
// (the Lucide names they replaced), so a page imports them the same way: `import { Plus, Trash2 } from "@/shared/icons"`.
// Props: `size` (px, 24 when not given), `className`, `style` and the usual SVG attributes; `strokeWidth` is accepted and
// ignored (the line is the scheme's: 2 on the 24 grid). `fill-current` on the class fills a closed shape (a pinned pin,
// the stop square). A new icon: draw it there, sync, add its line here.
import type { SVGProps } from "react";
import { markSvg } from "./marks";

export type IconProps = Omit<SVGProps<SVGSVGElement>, "ref" | "children"> & { size?: number | string; strokeWidth?: number | string; absoluteStrokeWidth?: boolean };
export type IconType = (props: IconProps) => React.JSX.Element;

function make(file: string): IconType {
  const body = (markSvg(`icons/${file}`) ?? "").replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");
  const Icon = ({ size = 24, strokeWidth: _line, absoluteStrokeWidth: _abs, ...rest }: IconProps) => (
    <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} viewBox="0 0 24 24" fill="none" aria-hidden={rest["aria-label"] ? undefined : true} {...rest} dangerouslySetInnerHTML={{ __html: body }} />
  );
  Icon.displayName = file;
  return Icon;
}

